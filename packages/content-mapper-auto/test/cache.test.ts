import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { test } from "node:test";
import { cacheKey, cachePathFor, formatCacheFile, readCache, withCacheLock, writeCache } from "../src/core/cache.ts";
import { resolveConfig } from "../src/core/config.ts";

const config = resolveConfig("/proj");

test("cache keys ignore line endings and trailing whitespace but not meaning", () => {
  const file = "/proj/src/a.auto";
  const key = cacheKey(config, file, "Export foo.\nIt returns 1.\n");
  assert.equal(cacheKey(config, file, "Export foo.  \r\nIt returns 1.\r\n\r\n"), key);
  assert.notEqual(cacheKey(config, file, "Export foo.\nIt returns 2.\n"), key);
  assert.notEqual(cacheKey(config, "/proj/src/b.auto", "Export foo.\nIt returns 1.\n"), key, "location matters (relative imports)");
  assert.notEqual(cacheKey(resolveConfig("/proj", { model: "x" }), file, "Export foo.\nIt returns 1.\n"), key);
});

test("cache paths mirror the source tree", () => {
  assert.equal(cachePathFor(config, "/proj/src/lib/a.auto"), path.resolve("/proj/.auto-cache/src/lib/a.auto.ts"));
  assert.equal(cachePathFor(config, "/elsewhere/a.auto"), path.resolve("/proj/.auto-cache/__up__/elsewhere/a.auto.ts"));
});

test("readCache distinguishes fresh, stale and missing entries", async () => {
  const dir = mkdtempSync(path.join(tmpdir(), "cma-cache-"));
  const file = path.join(dir, "x.ts");
  assert.deepEqual(await readCache(file, "a".repeat(64)), { kind: "missing" });
  await writeCache(file, formatCacheFile("src/x.auto", "a".repeat(64), "export const x = 1;\n\n"));
  const fresh = await readCache(file, "a".repeat(64));
  assert.equal(fresh.kind, "fresh");
  assert.match(fresh.kind === "fresh" ? fresh.code : "", /^\/\/ Generated by content-mapper-auto from "src\/x.auto"[\s\S]*export const x = 1;\n$/);
  assert.equal((await readCache(file, "b".repeat(64))).kind, "stale");
});

test("withCacheLock runs the producer once for concurrent callers", async () => {
  const dir = mkdtempSync(path.join(tmpdir(), "cma-lock-"));
  const file = path.join(dir, "y.ts");
  let produced = 0;
  let value: string | undefined;
  const attempt = () =>
    withCacheLock(
      file,
      "k",
      60_000,
      async () => value,
      async () => {
        produced++;
        await new Promise((r) => setTimeout(r, 300));
        value = "done";
        return value;
      },
    );
  assert.deepEqual(await Promise.all([attempt(), attempt(), attempt()]), ["done", "done", "done"]);
  assert.equal(produced, 1);
});
