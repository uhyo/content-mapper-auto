import { createHash, randomBytes } from "node:crypto";
import { mkdir, open, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import { hostname } from "node:os";
import path from "node:path";
import type { ResolvedConfig } from "./config.ts";

/**
 * Bump when the prompt or output format changes in a way that should invalidate existing caches.
 */
export const GENERATOR_VERSION = 1;

const KEY_LINE = /^\/\/ content-mapper-auto-key: ([0-9a-f]{64})$/m;

/** Normalizes a description so that line-ending and trailing-whitespace differences don't matter. */
export function normalizeDescription(content: string): string {
  return content.replace(/\r\n?/g, "\n").replace(/[ \t]+$/gm, "").trim() + "\n";
}

/** Project-relative path of a file using forward slashes, as shown to Claude and used in the cache. */
export function relativeSourcePath(config: ResolvedConfig, fileName: string): string {
  return path.relative(config.root, path.resolve(fileName)).split(path.sep).join("/");
}

/**
 * The cache key covers everything that determines what Claude is asked to do: the description, the
 * file's location (generated code may contain relative imports), the model, and the instructions.
 */
export function cacheKey(config: ResolvedConfig, fileName: string, content: string): string {
  const input = JSON.stringify({
    generator: GENERATOR_VERSION,
    path: relativeSourcePath(config, fileName),
    model: config.model ?? null,
    instructions: config.instructions,
    description: normalizeDescription(content),
  });
  return createHash("sha256").update(input).digest("hex");
}

/**
 * The cache mirrors the source tree: `src/foo.auto` is cached as `<cacheDir>/src/foo.auto.ts`,
 * which keeps generated code easy to review and diff when the cache is committed.
 */
export function cachePathFor(config: ResolvedConfig, fileName: string): string {
  const relative = relativeSourcePath(config, fileName)
    .split("/")
    .map((segment) => (segment === ".." ? "__up__" : segment))
    .join("/");
  return path.join(config.cacheDir, ...relative.split("/")) + ".ts";
}

export function formatCacheFile(sourcePath: string, key: string, code: string): string {
  return [
    `// Generated by content-mapper-auto from ${JSON.stringify(sourcePath)} using Claude.`,
    "// Edit the .auto file to change this module; edits made here are kept until it changes.",
    `// content-mapper-auto-key: ${key}`,
    "",
    code.replace(/\s+$/, ""),
    "",
  ].join("\n");
}

export type CacheLookup =
  | { kind: "fresh"; code: string }
  | { kind: "stale"; code: string }
  | { kind: "missing" };

/** Reads the cache file and checks whether it was generated for `key`. */
export async function readCache(cachePath: string, key: string): Promise<CacheLookup> {
  let text: string;
  try {
    text = await readFile(cachePath, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return { kind: "missing" };
    throw error;
  }
  const match = KEY_LINE.exec(text);
  return { kind: match?.[1] === key ? "fresh" : "stale", code: text };
}

/** Writes the cache file atomically, so readers never observe a partial module. */
export async function writeCache(cachePath: string, text: string): Promise<void> {
  await mkdir(path.dirname(cachePath), { recursive: true });
  const temp = `${cachePath}.${process.pid}.${randomBytes(4).toString("hex")}.tmp`;
  await writeFile(temp, text, "utf8");
  try {
    await rename(temp, cachePath);
  } catch (error) {
    await rm(temp, { force: true });
    throw error;
  }
}

interface LockOwner {
  pid: number;
  host: string;
  key: string;
}

function isAlive(pid: number): boolean {
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return (error as NodeJS.ErrnoException).code === "EPERM";
  }
}

async function isStaleLock(lockPath: string, maxAgeMs: number): Promise<boolean> {
  try {
    const [info, text] = await Promise.all([stat(lockPath), readFile(lockPath, "utf8")]);
    if (Date.now() - info.mtimeMs > maxAgeMs) return true;
    const owner = JSON.parse(text) as LockOwner;
    return owner.host === hostname() && !isAlive(owner.pid);
  } catch {
    // A lock that vanished is not stale (it is gone); an unreadable or half-written one is
    // treated as live until it ages out.
    return false;
  }
}

const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

/**
 * Runs `produce` while holding a cross-process lock for one cache file, so that the content mapper
 * (tsc or the editor) and Vite never run Claude for the same file at the same time. While another
 * process holds the lock, `poll` is called periodically; if it returns a value (because the other
 * process finished the work), that value is returned without running `produce`.
 */
export async function withCacheLock<T>(
  cachePath: string,
  key: string,
  maxAgeMs: number,
  poll: () => Promise<T | undefined>,
  produce: () => Promise<T>,
): Promise<T> {
  const lockPath = `${cachePath}.lock`;
  await mkdir(path.dirname(lockPath), { recursive: true });
  let delay = 100;
  for (;;) {
    try {
      const handle = await open(lockPath, "wx");
      try {
        const owner: LockOwner = { pid: process.pid, host: hostname(), key };
        await handle.writeFile(JSON.stringify(owner));
      } finally {
        await handle.close();
      }
      break;
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "EEXIST") throw error;
    }
    if (await isStaleLock(lockPath, maxAgeMs)) {
      await rm(lockPath, { force: true });
      continue;
    }
    await sleep(delay);
    delay = Math.min(delay * 2, 1000);
    const done = await poll();
    if (done !== undefined) return done;
  }
  try {
    // Another process may have finished between our cache check and acquiring the lock.
    return (await poll()) ?? (await produce());
  } finally {
    await rm(lockPath, { force: true });
  }
}
