import path from "node:path";
import type { Plugin, ResolvedConfig as ViteResolvedConfig } from "vite";
import { findPackageRoot, readTsconfigEntry, resolveConfig, validateOptions, type AutoOptions, type ResolvedConfig } from "../core/config.ts";
import { loadAutoModule } from "../core/index.ts";

export interface AutoPluginOptions extends AutoOptions {
  /**
   * The tsconfig whose `contentMappers` entry for content-mapper-auto supplies the default options
   * and the project root (and therefore the cache location), relative to the Vite root. Defaults to
   * `tsconfig.json`; project references are followed. Pass `false` to ignore tsconfig files.
   */
  tsconfig?: string | false;
  /** File extensions to handle. Defaults to the tsconfig entry's `extensions`, or `[".auto"]`. */
  extensions?: string[];
}

type TransformTs = (code: string, fileName: string) => Promise<{ code: string; map: unknown }>;

/** Strips TypeScript syntax with whichever transformer this Vite version ships (Oxc in Vite 8, esbuild before). */
async function loadTsTransformer(): Promise<TransformTs> {
  const vite = (await import("vite")) as Record<string, unknown>;
  if (typeof vite.transformWithOxc === "function") {
    const transformWithOxc = vite.transformWithOxc as (code: string, file: string, options: object) => Promise<{ code: string; map: unknown }>;
    return (code, fileName) => transformWithOxc(code, fileName, { lang: "ts", sourcemap: true });
  }
  const transformWithEsbuild = vite.transformWithEsbuild as (code: string, file: string, options: object) => Promise<{ code: string; map: unknown }>;
  return (code, fileName) => transformWithEsbuild(code, fileName, { loader: "ts", sourcemap: true });
}

/**
 * Vite plugin for `.auto` files: serves the TypeScript module generated by Claude from each
 * description. It shares its cache and configuration with the content-mapper-auto content mapper,
 * so the code that runs is exactly the code TypeScript type-checked.
 */
export default function autoPlugin(pluginOptions: AutoPluginOptions = {}): Plugin {
  const { tsconfig, extensions: explicitExtensions, ...explicit } = pluginOptions;
  let extensions: string[] = explicitExtensions ?? [".auto"];
  let configForFile: (fileName: string) => ResolvedConfig = () => {
    throw new Error("content-mapper-auto: plugin used before configResolved.");
  };
  let viteConfig: ViteResolvedConfig;
  let transformTs: Promise<TransformTs> | undefined;

  const matches = (id: string) => {
    const file = id.split("?", 1)[0]!;
    return extensions.some((extension) => file.endsWith(extension)) ? file : undefined;
  };

  return {
    name: "content-mapper-auto",
    enforce: "pre",

    configResolved(resolved) {
      viteConfig = resolved;
      const explicitResult = validateOptions(explicit);
      for (const problem of explicitResult.problems) {
        resolved.logger.warn(`[content-mapper-auto] plugin option ${problem.path.join(".") || "(root)"}: ${problem.message}`);
      }
      const entry = tsconfig === false ? undefined : readTsconfigEntry(path.resolve(resolved.root, tsconfig ?? "tsconfig.json"));
      if (entry?.extensions) {
        const fromTsconfig = validateOptions(entry.options);
        for (const problem of fromTsconfig.problems) {
          resolved.logger.warn(`[content-mapper-auto] ${path.relative(resolved.root, entry.configFileName)} option ${problem.path.join(".")}: ${problem.message}`);
        }
        if (!explicitExtensions && entry.extensions.length > 0) extensions = entry.extensions;
        // Same root as the content mapper (the tsconfig's directory) and same options, so both
        // compute the same cache keys and paths.
        const config = resolveConfig(path.dirname(entry.configFileName), { ...fromTsconfig.options, ...explicitResult.options });
        configForFile = () => config;
      } else {
        // Same fallback as the content mapper uses for files outside any configured project.
        configForFile = (fileName) => resolveConfig(findPackageRoot(path.dirname(fileName)), explicitResult.options);
      }
    },

    async transform(code, id) {
      const fileName = matches(id);
      if (!fileName) return null;
      const config = configForFile(fileName);
      const result = await loadAutoModule({
        fileName,
        content: code,
        config,
        onGenerate: (sourcePath) => viteConfig.logger.info(`[content-mapper-auto] Generating ${sourcePath} with Claude...`, { timestamp: true }),
      });
      // Hand-editing the cached module should trigger HMR just like editing the description.
      this.addWatchFile(result.cachePath);
      if (result.status !== "fresh") {
        this.error(`${path.relative(viteConfig.root, fileName)}: ${result.reason}`);
      }
      transformTs ??= loadTsTransformer();
      const output = await (await transformTs)(result.code, `${fileName}.ts`);
      return { code: output.code, map: output.map as never };
    },
  };
}

export { autoPlugin as auto };
